// Program to demonstrate the use of type casting

#include <iostream>
using namespace std;

int main() {
    float a = 2.34, d;
    int b = 3, c;

    c = (float)a;
    d = (int)b;

    cout << "float : " << c << endl;
    cout << "int : " << d << endl;
    
    return 0;
}   